// Harmonic Macro Relief crop correction: before/after evidence + pixel-identity of every other set.
// Usage: node v02-macro.mjs <url> <outdir> before|after
import { launch } from './cdp.mjs';
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
const [url, out, phase] = process.argv.slice(2);
const b = await launch(out + '/.chrome-macro', 9348);
await b.send('Page.navigate', { url }); await b.sleep(1500);
const setup = `
  const { renderArtwork } = await import('/src/artwork/renderArtwork.ts');
  const { ensureFonts } = await import('/src/artwork/fonts.ts');
  const { validateRecipe, DEFAULT_RECIPE } = await import('/src/instrument/recipe.ts');
  const { remix, recipeFromSeed } = await import('/src/instrument/remix.ts');
  await ensureFonts();
  // 32 UNSEEN Harmonic recipes: 24 from a fresh Remix chain (start seed never used before) + 8 hand-dial ranges
  // generated by a seeded rule (any Form/Rhythm a person can dial, incl. non-Remix ratios). No per-seed tuning.
  const cases = [];
  let r = recipeFromSeed({ ...DEFAULT_RECIPE, artist: 'Quiet Meridian', track: 'Lowland' }, 0x51de5eed);
  for (let i = 0; i < 24; i++) { r = remix(r); cases.push(validateRecipe({ ...r, mode: 'harmonic', palette: 5 })); }
  let s = 0x0dd1a1 >>> 0; const rnd = () => ((s = (Math.imul(s, 1664525) + 1013904223) >>> 0) / 4294967296);
  for (let i = 0; i < 8; i++) cases.push(validateRecipe({ ...DEFAULT_RECIPE, artist: 'Quiet Meridian', track: 'Lowland', mode: 'harmonic', palette: 5, form: 1 + ((rnd() * 8) | 0), rhythm: 1 + ((rnd() * 8) | 0), phase: (rnd() * 361) | 0, density: 1 + ((rnd() * 24) | 0), seed: (rnd() * 2 ** 32) >>> 0 }));
  const hashOf = async (c) => { const d = c.getContext('2d').getImageData(0, 0, c.width, c.height).data; const h = await crypto.subtle.digest('SHA-256', d); return [...new Uint8Array(h)].map((v) => v.toString(16).padStart(2, '0')).join(''); };
`;
// 1) pixel hashes: every set except Harmonic Macro must be unchanged (full + draft); Harmonic Macro listed for reference.
const hashes = await b.ev(`(async () => { ${setup}
  const res = {}, c = document.createElement('canvas'); c.width = c.height = 512; const x = c.getContext('2d');
  const recs = [DEFAULT_RECIPE, ...cases.slice(0, 5)];
  for (let p = 0; p < 6; p++) for (const mode of ['harmonic', 'radial']) for (const [k, rr] of recs.entries()) for (const q of ['full', 'draft']) {
    renderArtwork(x, validateRecipe({ ...rr, mode, palette: p }), 512, 512, q);
    res[\`p\${p}-\${mode}-\${k}-\${q}\`] = await hashOf(c);
  }
  return res; })()`);
writeFileSync(`${out}/macro-hashes-${phase}.json`, JSON.stringify(hashes, null, 1));
if (phase === 'after' && existsSync(`${out}/macro-hashes-before.json`)) {
  const before = JSON.parse(readFileSync(`${out}/macro-hashes-before.json`, 'utf8'));
  const keys = Object.keys(before), changed = keys.filter((k) => before[k] !== hashes[k]);
  const expected = (k) => k.startsWith('p5-harmonic-');
  const bad = changed.filter((k) => !expected(k)), others = keys.filter((k) => !expected(k));
  console.log(`IDENTITY: ${others.length - bad.length}/${others.length} non-Harmonic-Macro renders pixel-identical (full + draft, 5 other sets × 2 engines + Radial Macro, 6 recipes)`, bad.length ? 'CHANGED: ' + bad.join(', ') : '');
  console.log(`Harmonic Macro renders changed: ${changed.filter(expected).length}/${keys.filter(expected).length}`);
}
// 2) contact sheet of the 32 unseen Harmonic Macro cases
const sheet = await b.ev(`(async () => { ${setup}
  const cell = 400, pad = 10, lab = 26, cols = 8, rows = 4;
  const c = document.createElement('canvas'); c.width = cols * (cell + pad) + pad; c.height = rows * (cell + pad + lab) + pad; const x = c.getContext('2d');
  x.fillStyle = '#9a9a9a'; x.fillRect(0, 0, c.width, c.height);
  cases.forEach((rr, i) => { const X = pad + (i % cols) * (cell + pad), Y = pad + ((i / cols) | 0) * (cell + pad + lab) + lab;
    x.save(); x.translate(X, Y); renderArtwork(x, rr, cell, cell, 'full'); x.restore();
    x.fillStyle = '#111'; x.font = '600 14px ui-monospace, Menlo, monospace'; x.fillText('#' + (i + 1) + ' ' + rr.form + ':' + rr.rhythm + ' ' + rr.phase + '° d' + rr.density + (i >= 24 ? ' (dial)' : ''), X, Y - 8); });
  return c.toDataURL(); })()`);
b.saveDataUrl(`${out}/macro-harmonic-${phase}.png`, sheet);
console.log('wrote', `macro-harmonic-${phase}.png`, 'errors', b.errors.length ? b.errors : 'none');
b.close(); process.exit(0);
